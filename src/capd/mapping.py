"""Mapping is configuration: turn a state's mapping.yaml into the metric data contract views.

mapping.yaml names, for each contract record, the state's table and an expression for each field:

    records:
      application:
        table: ANALYTICS.ELIG.APPLICATIONS_V
        fields:
          application_id: APP_ID
          received_at: "CONVERT_TIMEZONE('America/Chicago', SUBMITTED_TS)"
          channel: { column: SUBMIT_CHANNEL_CD, values: { WEB: online, PHN: phone } }

`capd mapping views mapping.yaml` prints CREATE VIEW statements for C_APPLICATION and the others.
`capd mapping check mapping.yaml` lists unmapped fields and the metrics each one blocks.
"""

from __future__ import annotations

import yaml

CONTRACT = {
    "application": ("C_APPLICATION", ["application_id", "received_at", "channel", "programs", "expedited"]),
    "determination": ("C_DETERMINATION", ["application_id", "program", "result", "decided_at", "automated", "method"]),
    "notice": ("C_NOTICE", ["notice_id", "application_id", "notice_type", "channel", "generated_at", "sent_at", "automatic"]),
    "renewal": ("C_RENEWAL", ["renewal_id", "program", "due_date", "completed_at", "ex_parte", "prepopulated_sent"]),
    "work_item": ("C_WORK_ITEM", ["item_id", "item_type", "created_at", "status", "due_date"]),
    "appeal_transfer": ("C_APPEAL_TRANSFER", ["record_id", "record_type", "channel", "received_at", "completed_at", "status"]),
}
# Which contract fields each reference metric query reads (report-layer/sql/metrics/).
METRIC_FIELDS = {
    "ee05_automated_determinations (EE5)": ["determination.program", "determination.decided_at", "determination.automated"],
    "ee06_timeliness (EE6)": ["determination.program", "determination.decided_at", "determination.method",
                              "determination.application_id", "application.application_id", "application.received_at"],
    "ee09_automated_notices (EE9)": ["notice.generated_at", "notice.automatic"],
    "ee13_ex_parte_renewals (EE13)": ["renewal.program", "renewal.completed_at", "renewal.ex_parte"],
    "golive_snap_timeliness (GL03)": ["determination.program", "determination.decided_at", "determination.application_id",
                                      "application.application_id", "application.received_at", "application.expedited"],
    "golive_backlog (GL10)": ["work_item.item_type", "work_item.status", "work_item.due_date"],
}


def load(path) -> dict:
    data = yaml.safe_load(open(path, encoding="utf-8")) or {}
    records = data.get("records", {})
    unknown = sorted(set(records) - set(CONTRACT))
    if unknown:
        raise ValueError(f"unknown contract records in mapping: {unknown}; known: {sorted(CONTRACT)}")
    return records


def _expr(spec) -> str:
    if isinstance(spec, dict):
        col = spec["column"]
        whens = " ".join(f"WHEN '{k}' THEN '{v}'" for k, v in (spec.get("values") or {}).items())
        return f"CASE {col} {whens} ELSE {spec.get('default', 'NULL')} END" if whens else col
    return str(spec)


def views(records: dict) -> str:
    out = ["-- Generated by `capd mapping views`. Metric data contract views over the state's own tables."]
    for name, rec in records.items():
        view, fields = CONTRACT[name]
        cols = []
        for f in fields:
            spec = (rec.get("fields") or {}).get(f)
            cols.append(f"  {_expr(spec) if spec is not None else 'NULL'} AS {f}")
        where = f"\nWHERE {rec['where']}" if rec.get("where") else ""
        out.append(f"CREATE OR REPLACE VIEW {view} AS\nSELECT\n" + ",\n".join(cols) + f"\nFROM {rec['table']}{where};")
    return "\n\n".join(out) + "\n"


def check(records: dict) -> dict:
    mapped = {f"{n}.{f}" for n, rec in records.items() for f in (rec.get("fields") or {})}
    unmapped = sorted(f"{n}.{f}" for n, (_, fields) in CONTRACT.items() for f in fields if f"{n}.{f}" not in mapped)
    blocked = {m: sorted(set(fs) - mapped) for m, fs in METRIC_FIELDS.items() if set(fs) - mapped}
    ready = sorted(m for m in METRIC_FIELDS if m not in blocked)
    return {"unmapped": unmapped, "blockedMetrics": blocked, "readyMetrics": ready}
