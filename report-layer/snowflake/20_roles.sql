-- Roles mapped to state groups through single sign-on (SCIM or SAML group mapping).
-- Viewers see restricted items only as status and counts; the security role sees details.
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS CERT_VIEWER;     -- director, project manager, vendor
CREATE ROLE IF NOT EXISTS CERT_ACCEPTOR;   -- state product owner: records acceptance decisions
CREATE ROLE IF NOT EXISTS CERT_SECURITY;   -- state security officer
CREATE ROLE IF NOT EXISTS CERT_LOADER;     -- pipeline service identity: write-only
GRANT ROLE CERT_VIEWER TO ROLE CERT_ACCEPTOR;
GRANT ROLE CERT_VIEWER TO ROLE CERT_SECURITY;

USE ROLE SYSADMIN;
GRANT USAGE ON DATABASE CERTIFICATION TO ROLE CERT_VIEWER;
GRANT USAGE ON DATABASE CERTIFICATION TO ROLE CERT_LOADER;
GRANT USAGE ON SCHEMA CERTIFICATION.CERT TO ROLE CERT_VIEWER;
GRANT USAGE ON SCHEMA CERTIFICATION.CERT TO ROLE CERT_LOADER;
GRANT SELECT ON ALL VIEWS IN SCHEMA CERTIFICATION.CERT TO ROLE CERT_VIEWER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA CERTIFICATION.CERT TO ROLE CERT_VIEWER;

-- Loader: may only add pipeline evidence (and replace its own build's rows on rerun).
GRANT INSERT, DELETE ON TABLE CERTIFICATION.CERT.EVIDENCE TO ROLE CERT_LOADER;
GRANT INSERT, DELETE ON TABLE CERTIFICATION.CERT.BUNDLES TO ROLE CERT_LOADER;

-- Acceptor: records decisions.
GRANT INSERT ON TABLE CERTIFICATION.CERT.ACCEPTANCES TO ROLE CERT_ACCEPTOR;

-- Security: the restricted schema.
GRANT USAGE ON SCHEMA CERTIFICATION.CERT_RESTRICTED TO ROLE CERT_SECURITY;
GRANT SELECT, INSERT, UPDATE ON TABLE CERTIFICATION.CERT_RESTRICTED.SECURITY_FINDINGS TO ROLE CERT_SECURITY;

-- Secure view: viewers see counts and the oldest open age only, never details.
CREATE OR REPLACE SECURE VIEW CERTIFICATION.CERT.V_SECURITY_SUMMARY AS
SELECT severity, COUNT(*) AS open_findings, MAX(DATEDIFF('day', opened_at, CURRENT_TIMESTAMP())) AS oldest_open_days
FROM CERTIFICATION.CERT_RESTRICTED.SECURITY_FINDINGS
WHERE status <> 'closed'
GROUP BY severity
HAVING COUNT(*) >= 1;
GRANT SELECT ON VIEW CERTIFICATION.CERT.V_SECURITY_SUMMARY TO ROLE CERT_VIEWER;

-- Small-count suppression for aggregates built on case data: hide counts under 11.
CREATE OR REPLACE SECURE FUNCTION CERTIFICATION.CERT.SUPPRESS_SMALL(n NUMBER)
RETURNS NUMBER AS 'IFF(n BETWEEN 1 AND 10, NULL, n)';
