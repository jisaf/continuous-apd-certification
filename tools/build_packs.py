"""Generate pre-written example packs (Gherkin) from the catalog.

SIRT pack: one feature per SIRT section with a scenario outline for every SIRT row marked as a good
pre-write candidate (a single, clear, system-checkable behaviour). Each scenario carries the rule key,
the FNA ID, and the 7 CFR citation. Steps are written as pending placeholders: the vendor binds them to
its system through its adapter, and the state's policy staff supply the expected values.

Run:  python tools/build_packs.py
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "examples" / "packs"
SECTIONS = {
    "AP": "Initial application processing", "HH": "Household data", "S": "Status of households", "E": "Equity",
    "AR": "Authorized representative", "EI": "Earned income", "UI": "Unearned income", "EX": "Income exclusions",
    "R": "Resources", "MD": "Excess medical deduction", "DD": "Dependent care deduction", "SD": "Excess shelter deduction",
    "OD": "Other deductions", "CAT": "Categorical eligibility", "WR": "Work registration", "ET": "Employment and training",
    "ABS": "ABAWD time limits", "GRP": "Group facilities and homeless meal providers", "DIS": "Disaster SNAP", "CHG": "Change reporting",
    "MC": "Mass changes", "MJC": "Major changes", "C": "Claims", "RST": "Restoration of lost benefits", "CN": "Certification notices",
    "ED": "Edits and pending cases", "STA": "Staff alerts", "EB": "Eligibility and benefit actions",
    "TBA": "Transitional benefits alternative", "QC": "Quality control", "CR": "Case records", "PM": "Policy manuals",
    "SYS": "System performance", "MI": "Management information", "AW": "Administrative waivers", "DP": "Demonstration projects",
    "ISS": "Issuance", "RCN": "Reconciliation", "DM": "Data matching", "FNS": "FNS reports",
}


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def sirt_pack(rules: list[dict]) -> int:
    by_prefix: dict[str, list[dict]] = defaultdict(list)
    for r in rules:
        if r["set"] == "sirt" and r.get("prewrite"):
            by_prefix[r["sourceId"].split("-")[0]].append(r)
    folder = OUT / "sirt"
    folder.mkdir(parents=True, exist_ok=True)
    n = 0
    for prefix, items in sorted(by_prefix.items()):
        name = SECTIONS.get(prefix, prefix)
        lines = [
            f"# Pre-written SIRT pack: {name} ({prefix}). Generated by tools/build_packs.py from catalog {CATALOG_VERSION}. CC0.",
            "# Each scenario is a template: bind the steps to your system in your adapter, and have state policy",
            "# staff fill the Examples tables with expected values for your state's rules and the current year.",
            "",
            f"Feature: SNAP SIRT {prefix}: {name}",
            "",
        ]
        for r in items:
            n += 1
            cite = "; ".join(r["citations"]) or "Best practice"
            lines += [
                f"  @rule:{r['key']} @pending",
                f"  Scenario Outline: {r['sourceId']} {r['title'][:110].rstrip()}",
                f"    # FNA SIRT {r['sourceId']} ({r['source'].get('sheet')}, row {r['source'].get('row')}) — {cite}",
                f"    # Question: {r['text']}",
                "    Given a SNAP case set up as <setup>",
                "    When the system processes the case",
                "    Then the system shows <expected>",
                "",
                "    Examples:",
                "      | setup | expected |",
                "      | TODO  | TODO     |",
                "",
            ]
        (folder / f"{prefix.lower()}-{slug(name)}.feature").write_text("\n".join(lines))
    return n


def ee_pack(rules: list[dict]) -> int:
    folder = OUT / "cms-ee"
    folder.mkdir(parents=True, exist_ok=True)
    n = 0
    for r in rules:
        if r["set"] != "ee" or "test" not in r["gates"].get("ORR", []):
            continue
        n += 1
        text = "\n".join([
            f"# Pre-written CMS E&E pack: {r['sourceId']}. Generated by tools/build_packs.py. CC0.",
            "# ORR evidence: show the behaviour works before go-live. CR evidence is the production metric in the report layer.",
            "",
            f"@rule:{r['key']}",
            f"Feature: {r['sourceId']} {r['title']}",
            f"  # Outcome: {r['text']}",
            f"  # Default metrics (CR): {r.get('defaultMetrics', '').replace(chr(10), ' ')}",
            f"  # Regulatory sources: {'; '.join(r['citations'])}",
            "",
            "  @pending",
            "  Scenario Outline: The system meets the outcome for <situation>",
            "    Given an applicant or household in <situation>",
            "    When the system processes the case",
            "    Then the result is <expected>",
            "",
            "    Examples:",
            "      | situation | expected |",
            "      | TODO      | TODO     |",
            "",
        ])
        (folder / f"{r['sourceId'].lower()}-{slug(r['title'])[:50]}.feature").write_text(text)
    return n


def main() -> None:
    global CATALOG_VERSION
    cat = json.loads((ROOT / "src/capd/data/catalog/catalog.json").read_text())
    CATALOG_VERSION = cat["catalogVersion"]
    s = sirt_pack(cat["rules"])
    e = ee_pack(cat["rules"])
    (OUT / "README.md").write_text(f"""# Pre-written example packs

Generated by `python tools/build_packs.py` from catalog {CATALOG_VERSION}. CC0.

| Pack | Scenarios | What it covers |
| --- | --- | --- |
| [`sirt/`](sirt/) | {s} | Every SNAP SIRT row marked as a good pre-write candidate: one clear, system-checkable behaviour |
| [`cms-ee/`](cms-ee/) | {e} | Every CMS E&E outcome whose ORR evidence includes an automated test |

Every scenario already carries its `@rule:` key, its source ID, and its citation. They are templates, not
finished tests:

1. Copy the features you need into your test suite.
2. Bind the steps to your system in your step definitions or system adapter (see
   [`../sample-system/`](../sample-system/) for a working example).
3. Have state policy staff fill the `Examples` tables with expected values for your state's rules and the
   current fiscal year, then remove the `@pending` tag.

Scenarios tagged `@pending` should be excluded from runs until they are completed (for example
`pytest -m "not pending"` with pytest-bdd, or `--tags "not @pending"` with Cucumber).
""")
    print(f"wrote {s} SIRT scenarios and {e} E&E features to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
